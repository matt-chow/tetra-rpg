import { cloneBoard, clearLines, createEmptyBoard, pushGarbageRows } from "./board.js";
import { COLS, DEFAULT_RULES, ROWS } from "./constants.js";
import { createBagRNG, createPieceByType, createSeededRandom } from "./pieces.js";
import { tryRotateDetailed } from "./rotation.js";
import { computeAttack, detectTSpin, isDifficultClear } from "./attack.js";

export const NEXT_PREVIEW_COUNT = 5;

export function collides(board, piece, dx, dy) {
  const { shape, x, y } = piece;
  for (let py = 0; py < shape.length; py++) {
    for (let px = 0; px < shape[py].length; px++) {
      if (!shape[py][px]) continue;
      const nx = x + px + dx;
      const ny = y + py + dy;

      if (nx < 0 || nx >= COLS || ny >= ROWS) return true;
      if (ny >= 0 && board[ny][nx] !== 0) return true;
    }
  }
  return false;
}

export function mergePiece(board, piece) {
  const next = cloneBoard(board);
  const { shape, x, y, id } = piece;
  for (let py = 0; py < shape.length; py++) {
    for (let px = 0; px < shape[py].length; px++) {
      if (!shape[py][px]) continue;
      const gx = x + px;
      const gy = y + py;
      if (gy >= 0 && gy < ROWS && gx >= 0 && gx < COLS) {
        next[gy][gx] = id;
      }
    }
  }
  return next;
}

export function getGhostPiece(board, piece) {
  let drop = 0;
  while (!collides(board, piece, 0, drop + 1)) {
    drop += 1;
  }
  return { ...piece, y: piece.y + drop };
}

function hasPieceCellsAboveTop(piece) {
  const { shape, y } = piece;
  for (let py = 0; py < shape.length; py++) {
    if (y + py < 0 && shape[py].some(Boolean)) return true;
  }
  return false;
}

function createStats() {
  return {
    attack: 0, // lines generated by clears
    sent: 0, // lines that reached the opponent after cancelling
    cancelled: 0,
    received: 0,
    garbageTaken: 0, // lines actually inserted into this board
    tspins: 0,
    quads: 0,
    perfectClears: 0,
    maxCombo: 0,
    maxB2b: 0,
  };
}

// Engine actions, the only input surface used by players and bots alike.
export const ACTIONS = [
  "left",
  "right",
  "dasLeft",
  "dasRight",
  "down",
  "sonicDrop",
  "cw",
  "ccw",
  "180",
  "hold",
  "hardDrop",
];

// Deterministic rules for one board: 7-bag queue, hold, SRS, gravity, lock
// delay, line clears, T-spins, combo/B2B, attack and the incoming garbage
// queue. Time only advances through tick() (one fixed frame at FPS), so the
// same seed + the same calls always give the same game.
export function createGame({
  seed,
  random,
  garbageRandom,
  previewCount = NEXT_PREVIEW_COUNT,
  rules,
  initialBoard,
} = {}) {
  const r = { ...DEFAULT_RULES, ...rules };
  const bag = createBagRNG({ seed, random });
  // Separate stream so incoming garbage never shifts the piece sequence.
  const holeRandom = garbageRandom ?? createSeededRandom(`${seed ?? ""}:garbage`);
  const queue = [];
  let board = initialBoard ? cloneBoard(initialBoard) : createEmptyBoard();
  let piece = null;
  let holdType = null;
  let canHold = true;
  let piecesPlaced = 0;
  let lines = 0;
  let toppedOut = false;
  let topOutReason = null;
  let frame = 0;

  let gravityAcc = 0;
  let lockFrames = 0;
  let lockResets = 0;
  let lowestY = 0;
  let softDrop = { active: false, factor: 20 };
  let lastRotation = null; // { kickIndex, direction } while the last action was a rotation

  let combo = -1;
  let b2b = -1;
  let incoming = []; // { id, lines, ready, hole }
  let garbageId = 0;
  let lastHole = -1;
  let stats = createStats();
  let events = [];

  // The only place pieces leave the bag; keeps `previewCount` types visible.
  function takeNextType() {
    while (queue.length <= previewCount) queue.push(bag.next().type);
    return queue.shift();
  }

  function topOut(reason) {
    toppedOut = true;
    topOutReason = reason;
    events.push({ kind: "topOut", reason, frame });
  }

  // Returns false and tops out when the spawn position is blocked.
  function spawn(type) {
    const next = createPieceByType(type);
    gravityAcc = 0;
    lockFrames = 0;
    lockResets = 0;
    lowestY = next.y;
    lastRotation = null;
    if (collides(board, next, 0, 0)) {
      piece = next;
      topOut("blockOut");
      return false;
    }
    piece = next;
    events.push({ kind: "spawn", type, frame });
    return true;
  }

  function isGrounded() {
    return collides(board, piece, 0, 1);
  }

  // Successful move/rotate: TETR.IO-style move reset with a cap.
  function afterShift() {
    if (piece.y > lowestY) {
      lowestY = piece.y;
      lockResets = 0;
    }
    if (lockFrames > 0 || isGrounded()) {
      if (lockResets < r.lockResets) {
        lockFrames = 0;
        lockResets += 1;
      }
    }
  }

  function move(dx, dy) {
    if (toppedOut || collides(board, piece, dx, dy)) return false;
    piece = { ...piece, x: piece.x + dx, y: piece.y + dy };
    lastRotation = null;
    afterShift();
    return true;
  }

  // Gravity step: cancels a pending spin but never spends a lock reset.
  function fall() {
    if (collides(board, piece, 0, 1)) return false;
    piece = { ...piece, y: piece.y + 1 };
    lastRotation = null;
    if (piece.y > lowestY) {
      lowestY = piece.y;
      lockResets = 0;
    }
    return true;
  }

  function rotate(direction, options) {
    if (toppedOut) return false;
    const { piece: rotated, kickIndex } = tryRotateDetailed(board, piece, direction, options);
    if (rotated === piece) return false;
    piece = rotated;
    lastRotation = { kickIndex, direction };
    afterShift();
    return true;
  }

  function dropToFloor() {
    if (toppedOut) return 0;
    const ghost = getGhostPiece(board, piece);
    const rows = ghost.y - piece.y;
    if (rows > 0) {
      piece = ghost;
      lastRotation = null;
      afterShift();
    }
    return rows;
  }

  function receiveAttack(amount, { delay = r.garbageTravel } = {}) {
    if (toppedOut || amount <= 0) return null;
    let hole = Math.floor(holeRandom() * (lastHole < 0 ? COLS : COLS - 1));
    if (lastHole >= 0 && hole >= lastHole) hole += 1;
    lastHole = hole;
    const entry = { id: garbageId++, lines: amount, ready: delay, hole };
    incoming.push(entry);
    stats.received += amount;
    events.push({ kind: "garbageQueued", lines: amount, frame });
    return { ...entry };
  }

  // Outgoing attack first cancels this board's own incoming queue (oldest first).
  function cancelIncoming(attack) {
    let remaining = attack;
    while (remaining > 0 && incoming.length) {
      const head = incoming[0];
      const used = Math.min(head.lines, remaining);
      head.lines -= used;
      remaining -= used;
      if (head.lines === 0) incoming.shift();
    }
    return attack - remaining;
  }

  function insertReadyGarbage() {
    let cap = r.garbageCap;
    let added = 0;
    while (cap > 0 && incoming.length && incoming[0].ready <= 0) {
      const head = incoming[0];
      const take = Math.min(head.lines, cap);
      const pushed = pushGarbageRows(board, take, head.hole);
      board = pushed.board;
      added += take;
      cap -= take;
      head.lines -= take;
      if (head.lines === 0) incoming.shift();
      if (pushed.overflow) {
        topOut("garbage");
        break;
      }
    }
    stats.garbageTaken += added;
    return added;
  }

  // Locks a grounded piece, resolves clears/attack/garbage and spawns the next piece.
  // Returns null when nothing was locked.
  function lock() {
    if (toppedOut || !isGrounded()) return null;

    const lockedPiece = piece;
    const tspin = lastRotation ? detectTSpin(board, piece, lastRotation) : "none";
    const lockOut = hasPieceCellsAboveTop(piece);
    const cleared = clearLines(mergePiece(board, piece));
    board = cleared.board;
    const n = cleared.linesCleared;
    lines += n;
    piecesPlaced += 1;
    canHold = true;

    const perfectClear = n > 0 && board.every((row) => row.every((cell) => cell === 0));
    if (n > 0) {
      combo += 1;
      b2b = isDifficultClear(n, tspin) ? b2b + 1 : -1;
    } else {
      combo = -1;
    }
    const attack = computeAttack({ lines: n, tspin, combo, b2b, perfectClear }, r);
    const cancelled = cancelIncoming(attack);
    const sent = attack - cancelled;

    stats.attack += attack;
    stats.sent += sent;
    stats.cancelled += cancelled;
    if (tspin !== "none" && n > 0) stats.tspins += 1;
    if (n === 4) stats.quads += 1;
    if (perfectClear) stats.perfectClears += 1;
    stats.maxCombo = Math.max(stats.maxCombo, combo);
    stats.maxB2b = Math.max(stats.maxB2b, b2b);

    const result = {
      type: lockedPiece.type,
      piece: lockedPiece,
      linesCleared: n,
      tspin,
      combo,
      b2b,
      perfectClear,
      attack,
      cancelled,
      sent,
      garbageAdded: 0,
      lockOut,
      blockOut: false,
      frame,
    };

    // Pushed before the next spawn; filled in once garbage/spawn are resolved.
    const event = { kind: "lock" };
    events.push(event);
    if (lockOut) {
      topOut("lockOut");
    } else {
      // Clearing lines blocks garbage for this piece, like TETR.IO.
      if (n === 0) result.garbageAdded = insertReadyGarbage();
      if (!toppedOut) result.blockOut = !spawn(takeNextType());
    }

    Object.assign(event, result);
    return result;
  }

  function hold() {
    if (toppedOut || !canHold) return false;
    canHold = false;
    const incomingType = holdType ?? takeNextType();
    holdType = piece.type;
    spawn(incomingType);
    events.push({ kind: "hold", frame });
    return true;
  }

  // One fixed frame: garbage travel, gravity (or soft drop) and lock delay.
  function tick() {
    if (toppedOut) return null;
    frame += 1;
    for (const g of incoming) if (g.ready > 0) g.ready -= 1;

    if (softDrop.active && softDrop.factor === Infinity) {
      dropToFloor();
    } else {
      const speed = softDrop.active
        ? softDrop.factor * Math.max(r.gravity, r.softDropBase)
        : r.gravity;
      gravityAcc += speed;
      while (gravityAcc >= 1) {
        gravityAcc -= 1;
        if (!fall()) {
          gravityAcc = 0;
          break;
        }
      }
    }

    if (isGrounded()) {
      lockFrames += 1;
      if (lockFrames >= r.lockDelay) return lock();
    } else {
      lockFrames = 0;
    }
    return null;
  }

  function apply(action) {
    if (toppedOut) return false;
    switch (action) {
      case "left":
        return move(-1, 0);
      case "right":
        return move(1, 0);
      case "dasLeft": {
        let moved = false;
        while (move(-1, 0)) moved = true;
        return moved;
      }
      case "dasRight": {
        let moved = false;
        while (move(1, 0)) moved = true;
        return moved;
      }
      case "down":
        return move(0, 1);
      case "sonicDrop":
        return dropToFloor() > 0;
      case "cw":
      case "ccw":
      case "180":
        return rotate(action);
      case "hold":
        return hold();
      case "hardDrop":
        dropToFloor();
        return lock();
      default:
        throw new Error(`Unknown action: ${action}`);
    }
  }

  spawn(takeNextType());
  events = [];

  return {
    rules: r,

    getState() {
      return {
        board,
        piece,
        holdType,
        canHold,
        next: queue.slice(),
        piecesPlaced,
        lines,
        toppedOut,
        topOutReason,
        frame,
        combo,
        b2b,
        incoming: incoming.map((g) => ({ ...g })),
        lockFrames,
        lockResets,
        stats: { ...stats },
      };
    },

    isGrounded() {
      return !toppedOut && isGrounded();
    },

    move,
    rotate,
    // Moves the piece straight down as far as it goes; returns rows moved.
    dropToFloor,
    lock,
    // Swaps with hold (drawing from the queue when hold is empty). Once per piece.
    hold,
    tick,
    apply,
    receiveAttack,

    setSoftDrop(active, factor = softDrop.factor) {
      softDrop = { active: Boolean(active), factor };
    },

    // Events since the last drain: spawn, hold, lock, garbageQueued, topOut.
    drainEvents() {
      const out = events;
      events = [];
      return out;
    },

    pendingGarbage() {
      return incoming.reduce((sum, g) => sum + g.lines, 0);
    },
  };
}
